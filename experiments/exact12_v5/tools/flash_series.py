"""Run a fixed, balanced peer test; retain every completed match and replay."""
import argparse
import hashlib
import json
from pathlib import Path
import time
from botlab_peer import api,challenge,save,OUT,BOT,FLASH


def ready_version():
    manifest=json.loads((OUT.parent/'release_manifest.json').read_text())
    expected=manifest['artifacts']
    end=time.monotonic()+600
    while time.monotonic()<end:
        versions=api('/bots/'+BOT+'/versions')['results']
        version=next((v for v in versions if v['code']['sha256']==expected['code.zip']['sha256']
                      and v.get('models',{}).get('sha256')==expected['model.pt']['sha256']),None)
        if version is not None:
            save('platform_version.json',version)
            print(json.dumps({'version':version['id'],'status':version['status'],'stage':version.get('validation_stage')}),flush=True)
            if version['status']=='READY' and version['can_play']:return version
            if version['status'] in ['ERROR','REJECTED','DISABLED']:
                raise RuntimeError(json.dumps(version.get('validation_error'),ensure_ascii=False))
        time.sleep(5)
    raise RuntimeError('Validation deadline reached; saved upload may still be processing')


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--games',type=int,default=8)
    args=p.parse_args();assert args.games%2==0
    version=ready_version();records=[]
    protocol=[(color,pairs) for pairs in [0,1,2,3] for color in ['black','white']][:args.games]
    save('protocol.json',{'version':version['id'],'opponent':FLASH,'scheduled':protocol,
                          'note':'Balanced sides; random starts are independently generated by the platform, not identical paired openings.'})
    for i,(color,pairs) in enumerate(protocol):
        label='v5_%02d_%s_open%d'%(i+1,color,pairs)
        detail=challenge(version['id'],color,label,pairs)
        side=1 if color=='black' else -1
        result='invalid' if detail['end_reason']!='NORMAL' else 'draw' if not detail['winner'] else 'win' if detail['winner']==side else 'loss'
        records.append({'game':i+1,'side':side,'opening_pairs':pairs,'result':result,'match':detail['id'],
                        'steps':detail['step'],'end_reason':detail['end_reason'],'opening_actions':detail['opening_actions']})
        report={'version':version['id'],'opponent':FLASH,'games':len(records),
                'total':{r:sum(x['result']==r for x in records) for r in ['win','draw','loss','invalid']},'records':records}
        save('summary.json',report);print(json.dumps({'completed':len(records),'total':report['total']}),flush=True)
