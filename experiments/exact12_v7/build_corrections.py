"""Retain exact non-losing corrections from prior real games, not test games."""
import hashlib,json
from pathlib import Path
import numpy as np
from support.tactics import position


def mirrored(bits):
    return sum(((bits>>(7*c))&63)<<(7*(6-c)) for c in range(7))


def reverse_mask(mask):return sum(((mask>>c)&1)<<(6-c) for c in range(7))


def main():
    root=Path(__file__).resolve().parent;archive=np.load(root/'data/refinement.npz')
    raw={k:archive[k] for k in ['states','source','occupied','values','policies','scores']}
    table={};origins={}
    for i,state in enumerate(raw['states']):
        if str(raw['source'][i]) not in ['flash','replay','refutation']:continue
        if not 13<=raw['occupied'][i]<=24 or raw['values'][i]<0:continue
        board=state[0].astype(np.int8)-state[1].astype(np.int8);own,mask=position(board,1)
        key=own+mask;mirror=mirrored(own)+mirrored(mask)
        choices=sum(1<<c for c in np.flatnonzero(raw['policies'][i]>0))
        score=int(raw['values'][i]);assert score in [0,1]
        assert all(raw['scores'][i,c]==score for c in range(7) if choices&(1<<c))
        if mirror<key:key=mirror;choices=reverse_mask(choices)
        if key in table:
            assert table[key][1]==score;choices|=table[key][0]
        table[key]=(choices,score)
        origins.setdefault(key,[]).append(int(i))
    header='''"""Exact WDL corrections from previous training/development games.
Generated by build_corrections.py from offline proof labels. This is a small
selective extension of the opening book, not a learned neural-network layer.
External held-out states and new v6 platform matches are not in this table.
"""
_TABLE = {\n'''
    entries=''.join('    %d: (%d, %d),\n'%(key,*table[key]) for key in sorted(table))
    footer='''}

def lookup(own, mask):
    reverse_own = sum(((own >> (7*c)) & 63) << (7*(6-c)) for c in range(7))
    reverse_mask = sum(((mask >> (7*c)) & 63) << (7*(6-c)) for c in range(7))
    forward = own + mask
    reverse = reverse_own + reverse_mask
    flipped = reverse < forward
    entry = _TABLE.get(reverse if flipped else forward)
    if entry is None:
        return None
    moves, value = entry
    if flipped:
        moves = sum(((moves >> c) & 1) << (6-c) for c in range(7))
    return moves, value
'''
    path=root/'support/corrections.py';path.write_text(header+entries+footer)
    report={'entries':len(table),'source_dataset_sha256':hashlib.sha256((root/'data/refinement.npz').read_bytes()).hexdigest(),
            'only_proved_nonlosing_moves':True,'depth_range':[13,24],'sources':['flash','replay','refutation'],
            'includes_internal_development_labels':True,'external_test_states_excluded':True}
    (root/'runs/corrections.json').write_text(json.dumps(report,indent=2));print(json.dumps(report))


if __name__=='__main__':main()
